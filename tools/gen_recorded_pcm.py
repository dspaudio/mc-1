"""Generate legacy PCM-ID descriptors that alias the real LA attack bank."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import sys
from typing import Final

ROOT: Final = Path(__file__).resolve().parents[1]


def main() -> None:
    """Keep old source IDs without duplicating the new multi-zone PCM arrays."""
    manifest = json.loads((ROOT / "assets/hybrid/manifest.json").read_text())
    zones = manifest["zones"]
    descriptors = []
    measurements = []
    for family in range(17):
        zone = min((entry for entry in zones if entry["family"] == family),
                   key=lambda entry: abs(entry["root"] - 60))
        index = zone["index"]
        frames = zone["attack_frames"]
        levels = [f"{{mc_hybrid_attack_{index}_{mip},{frames >> mip},0,0}}"
                  for mip in range(7)]
        descriptors.append("    {{" + ",".join(levels) + "}},")
        measurements.append({"family": family, "zone": index, "root": zone["root"],
                             "frames": frames, "source_sha256": zone["source_sha256"]})
    header = [
        "/* Generated by tools/gen_recorded_pcm.py; GPL-3.0-only, recordings CC0-1.0. */",
        "/* Legacy source IDs alias the hybrid attacks; no duplicate PCM or sample loops. */",
        "#ifndef MC_RECORDED_PCM_H", "#define MC_RECORDED_PCM_H",
        '#include "hybrid_pcm.h"', "#include <stdint.h>",
        "#ifndef MC_RECORDED_SAMPLES", "#define MC_RECORDED_SAMPLES 17", "#endif",
        "typedef struct { const int16_t *data; uint16_t length, loop_start, loop_end; } McRecordedLevel;",
        "typedef struct { McRecordedLevel levels[7]; } McRecordedSample;",
        "static const McRecordedSample mc_recorded[MC_RECORDED_SAMPLES] = {",
        *descriptors, "};", "#endif", "",
    ]
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src/recorded_pcm.h"
    output.write_text("\n".join(header))
    report = {"header_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
              "pcm_bytes": 0, "table_bytes_32bit": 17 * 7 * 12,
              "sources": measurements}
    metrics = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "build/recorded-pcm-report.json"
    metrics.parent.mkdir(parents=True, exist_ok=True)
    metrics.write_text(json.dumps(report, indent=2) + "\n")
    print(f"{output}: 17 source aliases, no duplicate PCM; {report['table_bytes_32bit']} metadata bytes")


if __name__ == "__main__":
    main()
