"""Original mathematical attacks and band-limited oscillator tables. No recordings."""
import math
from pathlib import Path
import random
root = Path(__file__).resolve().parents[1]
out = ['/* SPDX-License-Identifier: GPL-3.0-only */', '/* Generated by tools/gen_assets.py; original dspaudio waveforms. */']
def array(name, rows, typ='int16_t'):
    if isinstance(rows[0], list):
        out.append(f'static const {typ} {name}[{len(rows)}][{len(rows[0])}] = {{')
        for row in rows:
            out.append('{' + ','.join(map(str,row)) + '},')
    else:
        out.append(f'static const {typ} {name}[{len(rows)}] = {{')
        for i in range(0,len(rows),16): out.append(','.join(map(str,rows[i:i+16]))+',')
    out.append('};')
array('mc_sine', [round(16383*math.sin(2*math.pi*i/1024)) for i in range(1024)])
for wave in ['saw', 'square']:
    rows=[]
    for harmonics in [64,32,16,8,4,2,1]:
        hs=range(1,harmonics+1,1 if wave=='saw' else 2)
        vals=[sum(math.sin(2*math.pi*h*i/256)/h for h in hs) for i in range(256)]
        rows.append([round(v/max(map(abs,vals))*14000) for v in vals])
    array('mc_'+wave,rows)
rng=random.Random(0x4d43464d)
rows=[]
for kind in range(12):
    row=[]
    for i in range(512):
        t=i/22050
        env=math.exp(-i/(70+kind*35))*(1-i/512)
        noise=rng.uniform(-1,1)
        if kind==0: v=math.sin(2*math.pi*(950*t+1200*t*t))*.7+noise*.3
        elif kind==1: v=math.sin(2*math.pi*2093*t)*.5+math.sin(2*math.pi*3327*t)*.3+noise*.2
        elif kind==2: v=noise*.8+math.sin(2*math.pi*523*t)*.2
        elif kind==3: v=math.sin(2*math.pi*784*t)*math.sin(2*math.pi*1121*t)
        elif kind==4: v=math.sin(2*math.pi*261.63*t)+noise*.15
        elif kind==5: v=math.sin(2*math.pi*1568*t)*.5+math.sin(2*math.pi*2571*t)*.4
        elif kind==6: v=(math.sin(2*math.pi*523*t)+.35*math.sin(2*math.pi*1572*t))*math.exp(-i/180)+noise*.18*math.exp(-i/30)
        elif kind==7: v=.6*math.sin(2*math.pi*784*t)+.25*math.sin(2*math.pi*1831*t)+noise*.15*math.exp(-i/45)
        elif kind==8: v=.55*math.sin(2*math.pi*523*t)+.3*math.sin(2*math.pi*1046*t)+.15*math.sin(2*math.pi*1569*t)
        elif kind==9: v=.55*noise+.3*math.sin(2*math.pi*523*t)+.15*math.sin(2*math.pi*1569*t)
        elif kind==10: v=(.5*math.sin(2*math.pi*523*t)+.25*math.sin(2*math.pi*1046*t)+.15*math.sin(2*math.pi*1569*t))*(1-math.exp(-i/40))
        else: v=.6*math.sin(2*math.pi*1046*t)+.3*math.sin(2*math.pi*2911*t)*math.exp(-i/100)
        row.append(round(max(-1,min(1,v*env))*16000))
    rows.append(row)
# Original additive transients: organ, keys, vowel-like tones, hits and sequences.
# Each partial is (frequency Hz, amplitude); no sampled or vendor material is used.
for partials, noise_mix, decay, rise, sweep in [
    (((261.63,.5),(523.26,.3),(784.89,.2)), .08, 190, 0, 0),
    (((261.63,.45),(523.26,.3),(1308.15,.2)), .05, 240, 0, 0),
    (((261.63,.55),(788,.25),(1327,.15)), .12, 170, 0, -80),
    (((523.26,.5),(1469,.25),(2616,.2)), .03, 220, 0, 120),
    (((261.63,.15),(784.89,.5),(1308.15,.3)), .04, 300, 12, 0),
    (((261.63,.2),(523.26,.3),(1831.41,.4)), .22, 270, 18, 0),
    (((261.63,.25),(1046.52,.45),(2354.67,.25)), .08, 320, 24, -150),
    (((261.63,.4),(523.26,.3),(784.89,.25)), .2, 95, 0, -900),
    (((392,.6),(1031,.25),(2179,.1)), .15, 65, 0, -350),
    (((523.26,.45),(1413,.35),(2261,.15)), .03, 150, 0, 0),
    (((523.26,.5),(2093.04,.25),(3662.82,.2)), .1, 85, 0, 650),
    (((261.63,.45),(1308.15,.3),(2877.93,.2)), .18, 50, 0, -600),
]:
    row=[]
    for i in range(512):
        t=i/22050
        env=math.exp(-i/decay)*(1-i/512)
        if rise: env*=1-math.exp(-i/rise)
        v=sum(amplitude*math.sin(2*math.pi*(frequency*t+sweep*t*t))
              for frequency,amplitude in partials)
        v+=rng.uniform(-1,1)*noise_mix*math.exp(-i/24)
        row.append(round(max(-1,min(1,v*env))*16000))
    rows.append(row)
array('mc_attack',rows)
array('mc_frequency',[round(440*2**((n-69)/12)*2**32/44100) for n in range(109)],'uint32_t')
array('mc_pcm_rate',[round(.5*2**((n-60)/12)*65536) for n in range(109)],'uint32_t')
(root/'src/tables.h').write_text('\n'.join(out)+'\n')
print('Generated 24 x 512 original PCM attacks (24576 bytes), oscillator LUTs and tuning.')
